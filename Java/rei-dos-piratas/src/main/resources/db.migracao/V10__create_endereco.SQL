-- V10: Criação da tabela ENDERECO
CREATE TABLE ENDERECO (
    id              BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    numero          INTEGER,
    cep             VARCHAR(8)  NOT NULL,
    logradouro      VARCHAR(70) NOT NULL,
    bairro          VARCHAR(50) NOT NULL,
    endereco_ativo  BOOLEAN    DEFAULT TRUE NOT NULL,
    cidade_id       BIGINT,
    cliente_id      BIGINT,
    empresa_id      BIGINT UNIQUE,
    CONSTRAINT fk_end_cidade  FOREIGN KEY (cidade_id)  REFERENCES CIDADES(id),
    CONSTRAINT fk_end_cliente FOREIGN KEY (cliente_id) REFERENCES CLIENTES(id),
    CONSTRAINT fk_end_empresa FOREIGN KEY (empresa_id) REFERENCES DADOS_EMPRESA(id)
);

