-- V11: Criação da tabela PRODUTOS
CREATE TABLE PRODUTOS (
    id               BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nome             VARCHAR(150) NOT NULL UNIQUE,
    descricao        VARCHAR(500) NOT NULL,
    autor            VARCHAR(100) NOT NULL,
    categoria        VARCHAR(50)  NOT NULL,
    endereco_imagem  VARCHAR(255) NOT NULL,
    preco            NUMERIC(10,2)  NOT NULL,
    preco_original   NUMERIC(10,2)  NOT NULL,
    estoque          INTEGER        NOT NULL,
    altura           NUMERIC(10,2),
    largura          NUMERIC(10,2),
    profundidade     NUMERIC(10,2),
    peso             NUMERIC(10,2),
    condicao         VARCHAR(255) NOT NULL,
    funcionario_id   BIGINT,
    CONSTRAINT fk_prod_funcionario FOREIGN KEY (funcionario_id) REFERENCES FUNCIONARIOS(id)
);

