-- V42: Estornos de pagamento (cancelamento do pedido ou devolucao de itens); um pagamento pode ter varios.
CREATE TABLE ESTORNOS (
    id                      BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    pagamento_id            BIGINT        NOT NULL,
    origem                  VARCHAR(20)   NOT NULL,
    devolucao_id            BIGINT,
    valor                   NUMERIC(12,2) NOT NULL,
    status                  VARCHAR(30)   NOT NULL,
    url_solicitacao_boleto  VARCHAR(500),
    motivo_falha            VARCHAR(255),
    data_solicitacao        TIMESTAMP     NOT NULL,
    data_conclusao          TIMESTAMP,
    CONSTRAINT fk_estornos_pagamento FOREIGN KEY (pagamento_id) REFERENCES PAGAMENTOS (id),
    CONSTRAINT fk_estornos_devolucao FOREIGN KEY (devolucao_id) REFERENCES DEVOLUCOES (id),
    CONSTRAINT uk_estornos_devolucao UNIQUE (devolucao_id),
    CONSTRAINT ck_estornos_origem CHECK (origem IN ('CANCELAMENTO', 'DEVOLUCAO')),
    CONSTRAINT ck_estornos_status CHECK (status IN ('SOLICITADO', 'EM_ANDAMENTO', 'AGUARDANDO_CLIENTE', 'CONCLUIDO', 'NEGADO', 'FALHOU')),
    CONSTRAINT ck_estornos_valor CHECK (valor > 0)
);

CREATE INDEX idx_estornos_pagamento ON ESTORNOS (pagamento_id);
