-- V38: Cartoes tokenizados do cliente (Asaas) e pagamento do pedido (um por pedido)
-- Dados do cartao (numero/CVV) nunca sao armazenados: apenas o token, os 4 ultimos digitos e a bandeira.
CREATE TABLE CARTOES_CLIENTE (
    id               BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    cliente_id       BIGINT       NOT NULL,
    token            VARCHAR(100) NOT NULL,
    ultimos_digitos  VARCHAR(4)   NOT NULL,
    bandeira         VARCHAR(30)  NOT NULL,
    ativo            BOOLEAN      DEFAULT TRUE NOT NULL,
    data_cadastro    TIMESTAMP    NOT NULL,
    CONSTRAINT fk_cartoes_cliente_cliente FOREIGN KEY (cliente_id) REFERENCES CLIENTES (id),
    CONSTRAINT uk_cartoes_cliente_token UNIQUE (token)
);

CREATE INDEX idx_cartoes_cliente_cliente ON CARTOES_CLIENTE (cliente_id);

CREATE TABLE PAGAMENTOS (
    id                 BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    pedido_id          BIGINT        NOT NULL,
    tipo               VARCHAR(20)   NOT NULL,
    status             VARCHAR(20)   NOT NULL,
    id_cobranca        VARCHAR(50),
    valor              NUMERIC(12,2) NOT NULL,
    valor_liquido      NUMERIC(12,2),
    parcelas           INTEGER       DEFAULT 1 NOT NULL,
    cartao_cliente_id  BIGINT,
    motivo_recusa      VARCHAR(255),
    data_criacao       TIMESTAMP     NOT NULL,
    data_confirmacao   TIMESTAMP,
    CONSTRAINT fk_pagamentos_pedido FOREIGN KEY (pedido_id) REFERENCES PEDIDOS (id),
    CONSTRAINT fk_pagamentos_cartao_cliente FOREIGN KEY (cartao_cliente_id) REFERENCES CARTOES_CLIENTE (id),
    CONSTRAINT uk_pagamentos_pedido UNIQUE (pedido_id),
    CONSTRAINT uk_pagamentos_id_cobranca UNIQUE (id_cobranca),
    CONSTRAINT ck_pagamentos_tipo CHECK (tipo IN ('PIX', 'BOLETO', 'CREDIT_CARD')),
    CONSTRAINT ck_pagamentos_status CHECK (status IN ('PENDENTE', 'CONFIRMADO', 'RECEBIDO', 'RECUSADO', 'CANCELADO', 'ESTORNADO')),
    CONSTRAINT ck_pagamentos_parcelas CHECK (parcelas >= 1)
);
