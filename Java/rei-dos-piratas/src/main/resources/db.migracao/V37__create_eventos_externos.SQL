-- V37: Registro dos eventos recebidos de sistemas externos (Asaas, Melhor Envio...) para idempotencia e acompanhamento do processamento
CREATE TABLE EVENTOS_EXTERNOS (
    id                    BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    origem                VARCHAR(30)  NOT NULL,
    id_externo            VARCHAR(100) NOT NULL,
    tipo_evento           VARCHAR(60)  NOT NULL,
    data_recebimento      TIMESTAMP    NOT NULL,
    status_processamento  VARCHAR(20)  NOT NULL,
    payload               TEXT         NOT NULL,
    tentativas            INTEGER      DEFAULT 0 NOT NULL,
    processando_ate       TIMESTAMP,
    CONSTRAINT uk_eventos_externos_origem_id_externo UNIQUE (origem, id_externo),
    CONSTRAINT ck_eventos_externos_origem CHECK (origem IN ('ASAAS', 'MELHOR_ENVIO')),
    CONSTRAINT ck_eventos_externos_status CHECK (status_processamento IN ('PENDENTE', 'PROCESSANDO', 'PROCESSADO', 'FALHA'))
);
