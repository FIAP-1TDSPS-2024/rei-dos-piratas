-- V13: Criação da tabela PEDIDOS
CREATE TABLE PEDIDOS (
    id                    NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    data_pedido           DATE          NOT NULL,
    data_entrega          DATE,
    data_previsao_entrega DATE,
    data_cancelamento     DATE,
    valor_total           NUMBER(12,2)  NOT NULL,
    valor_frete           NUMBER(12,2)  NOT NULL,
    status                VARCHAR2(50)  NOT NULL,
    cliente_id            NUMBER        NOT NULL,
    endereco_entrega_id   NUMBER        NOT NULL,
    servico_entrega       NUMBER,
    nota_fiscal           VARCHAR2(255),
    pedido_frete          VARCHAR2(36),
    CONSTRAINT fk_ped_cliente    FOREIGN KEY (cliente_id)          REFERENCES CLIENTES(id),
    CONSTRAINT fk_ped_endereco   FOREIGN KEY (endereco_entrega_id) REFERENCES ENDERECO(id)
);

