-- V13: Criação da tabela PEDIDOS
CREATE TABLE PEDIDOS (
    id                    BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    data_pedido           DATE          NOT NULL,
    data_entrega          DATE,
    data_previsao_entrega DATE,
    data_cancelamento     DATE,
    valor_total           NUMERIC(12,2)  NOT NULL,
    valor_frete           NUMERIC(12,2)  NOT NULL,
    status                VARCHAR(50)  NOT NULL,
    cliente_id            BIGINT        NOT NULL,
    endereco_entrega_id   BIGINT        NOT NULL,
    servico_entrega       BIGINT,
    nota_fiscal           VARCHAR(255),
    pedido_frete          VARCHAR(36),
    CONSTRAINT fk_ped_cliente    FOREIGN KEY (cliente_id)          REFERENCES CLIENTES(id),
    CONSTRAINT fk_ped_endereco   FOREIGN KEY (endereco_entrega_id) REFERENCES ENDERECO(id)
);

