-- V12: Criação da tabela CARRINHO_PRODUTO (itens do carrinho)
CREATE TABLE CARRINHO_PRODUTO (
    id          NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    produto_id  NUMBER       NOT NULL,
    carrinho_id NUMBER       NOT NULL,
    quantidade  NUMBER       NOT NULL,
    CONSTRAINT fk_cp_produto  FOREIGN KEY (produto_id)  REFERENCES PRODUTOS(id),
    CONSTRAINT fk_cp_carrinho FOREIGN KEY (carrinho_id) REFERENCES CARRINHOS(id)
);

