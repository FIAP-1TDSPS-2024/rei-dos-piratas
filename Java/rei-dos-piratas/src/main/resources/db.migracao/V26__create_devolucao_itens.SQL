CREATE TABLE DEVOLUCAO_ITENS (
    id                BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    devolucao_id      BIGINT NOT NULL,
    pedido_produto_id BIGINT NOT NULL,
    quantidade        INTEGER NOT NULL,
    CONSTRAINT fk_dev_item_devolucao FOREIGN KEY (devolucao_id) REFERENCES DEVOLUCOES(id),
    CONSTRAINT fk_dev_item_pedido_prod FOREIGN KEY (pedido_produto_id) REFERENCES PEDIDO_PRODUTO(id)
);

