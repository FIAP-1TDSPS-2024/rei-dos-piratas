-- V11: Criação da tabela PRODUTOS
CREATE TABLE PRODUTOS (
    id               NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nome             VARCHAR2(150) NOT NULL UNIQUE,
    descricao        VARCHAR2(500) NOT NULL,
    autor            VARCHAR2(100) NOT NULL,
    categoria        VARCHAR2(50)  NOT NULL,
    endereco_imagem  VARCHAR2(255) NOT NULL,
    preco            NUMBER(10,2)  NOT NULL,
    preco_original   NUMBER(10,2)  NOT NULL,
    estoque          NUMBER        NOT NULL,
    altura           NUMBER(10,2),
    largura          NUMBER(10,2),
    profundidade     NUMBER(10,2),
    peso             NUMBER(10,2),
    condicao         VARCHAR2(255) NOT NULL,
    funcionario_id   NUMBER,
    CONSTRAINT fk_prod_funcionario FOREIGN KEY (funcionario_id) REFERENCES FUNCIONARIOS(id)
);

